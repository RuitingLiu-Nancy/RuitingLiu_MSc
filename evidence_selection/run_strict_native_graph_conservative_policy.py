#!/usr/bin/env python3
"""Nested-OOF conservative one-swap policies for strict native Graph candidates.

This is a development-only, full-information one-step contextual policy
experiment.  It consumes the already frozen strict-native provenance ledger,
the fully judged D8+Depth4+Graph4 pool, and the exact query-grouped splits used
by the preceding strict-SBERT selector experiment.

The experiment deliberately keeps the following boundaries explicit:

* ``mixed_lambdamart_depth`` is frozen before this experiment and is never
  re-selected from policy outcomes;
* outer-validation baseline sets are exact reproductions of the prior OOF
  selector, while outer-train baseline features are generated by inner OOF;
* action eligibility is utility-blind and every eligible replacement receives
  its full-information reward only after its feature vector is frozen;
* every model has an implicit NO-OP action with fixed score zero and a
  conservative threshold selected only from inner query-grouped OOF;
* repeated OOF rows are averaged within the same query before bootstrap;
* frozen test paths and external model calls are rejected.

The implementation is not PPO, GRPO, REINFORCE, a multi-step agent, or a
logged-bandit estimator.  The linear and MLP arms directly optimize the known
expected one-step reward table under a softmax policy.
"""
